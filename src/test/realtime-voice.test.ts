  vi.doMock("@/lib/automation/tools", async (orig) => ({ ...(await orig() as object), invokeTool: async (...a: unknown[]) => { invoked.push(a); return { status: "ok", output: "tarea creada", trusted: true }; } }));
  vi.resetModules();
  vi.doMock("@/lib/core/executor", () => ({ credentialsFor: async () => ({ creds: { apiKey: "unit-azure-key", endpoint: "https://mi.openai.azure.com/openai/v1", deployment: "gpt-realtime-dep" } }) }));
  const { startRealtime: start } = await import("@/lib/realtime-voice");
  const core = { repo: { buildContext: vi.fn(async () => "ctx"), getModelPrice: vi.fn(async () => null), budgetStatus: vi.fn(async () => ({ level: "ok", spentUsd: 0, limitUsd: null })), recordCost: vi.fn(async () => undefined), sql: { run: vi.fn(async () => undefined) } } } as unknown as Core;
  const model = { capabilities: ["speech.realtime"], provider_kind: "azure_openai", provider_id: "az", remote_id: "gpt-realtime" } as ModelWithCaps;
  const logs: string[] = [];
